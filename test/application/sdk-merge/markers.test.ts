import { TextDecoder, TextEncoder } from 'node:util';
import { expect } from 'chai';
import { hasConflictMarkers, relabelMarkers } from '../../../src/application/sdk-merge/markers.js';

const bytes = (text: string) => new TextEncoder().encode(text);
const text = (content: Uint8Array) => new TextDecoder().decode(content);

const OURS = 'a'.repeat(40);
const THEIRS = 'b'.repeat(40);

describe('relabelMarkers', () => {
  it('names the sides where git named its commits, and changes nothing else', () => {
    const merged = `a\n<<<<<<< ${OURS}\nB\n=======\nX\n>>>>>>> ${THEIRS}\nc\n`;

    expect(text(relabelMarkers(bytes(merged)))).to.equal(
      'a\n<<<<<<< Your changes\nB\n=======\nX\n>>>>>>> Generated by APIMatic\nc\n'
    );
  });

  it('returns the same bytes when there is nothing to relabel', () => {
    const content = bytes('<<<<<<< not a sha\nplain\n');

    expect(relabelMarkers(content)).to.equal(content);
  });
});

describe('hasConflictMarkers', () => {
  it('finds the markers a conflicted run writes, whatever the line ending, and nothing else', () => {
    expect(hasConflictMarkers(bytes('a\n<<<<<<< Your changes\nb\n=======\nc\n>>>>>>> Generated by APIMatic\n'))).to.be
      .true;
    expect(hasConflictMarkers(bytes('a\r\n>>>>>>> Generated by APIMatic\r\n'))).to.be.true;
    expect(hasConflictMarkers(bytes(`<<<<<<< ${OURS}\n`))).to.be.false;
    expect(hasConflictMarkers(bytes('=======\n'))).to.be.false;
    expect(hasConflictMarkers(new Uint8Array([0xff, 0xfe, 0x3c]))).to.be.false;
  });
});
