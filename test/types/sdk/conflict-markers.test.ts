import { Buffer } from 'node:buffer';
import { TextDecoder, TextEncoder } from 'node:util';
import { expect } from 'chai';
import { relabelMarkers, settleMarkers } from '../../../src/types/sdk/conflict-markers.js';

const bytes = (text: string) => new TextEncoder().encode(text);
const text = (content: Uint8Array) => new TextDecoder().decode(content);

const OURS = 'a'.repeat(40);
const THEIRS = 'b'.repeat(40);

describe('relabelMarkers', () => {
  it('names the sides where git named its commits, and changes nothing else', () => {
    const merged = `a\n<<<<<<< ${OURS}\nB\n=======\nX\n>>>>>>> ${THEIRS}\nc\n`;

    expect(text(relabelMarkers(bytes(merged)))).to.equal(
      'a\n<<<<<<< Your changes\nB\n=======\nX\n>>>>>>> Generated by APIMatic\nc\n'
    );
  });

  it('returns the same bytes when there is nothing to relabel', () => {
    const content = bytes('<<<<<<< not a sha\nplain\n');

    expect(relabelMarkers(content)).to.equal(content);
  });

  it('reads the labels git writes after a rename, which name the path too, and on CRLF lines', () => {
    const merged = `<<<<<<< ${OURS}:old/path.ts\r\nB\r\n=======\r\nX\r\n>>>>>>> ${THEIRS}:new/path.ts\r\n`;

    expect(text(relabelMarkers(bytes(merged)))).to.equal(
      '<<<<<<< Your changes\r\nB\r\n=======\r\nX\r\n>>>>>>> Generated by APIMatic\r\n'
    );
  });

  it('keeps every byte of a file that is not UTF-8, relabelling only the marker lines', () => {
    const latin1 = Buffer.concat([
      Buffer.from(`caf\xe9\n<<<<<<< ${OURS}\n`, 'latin1'),
      Buffer.from([0xff, 0xfe, 0x0a]),
      Buffer.from(`=======\nX\n>>>>>>> ${THEIRS}\n`, 'latin1')
    ]);

    const relabelled = Buffer.from(relabelMarkers(new Uint8Array(latin1)));

    expect(relabelled.subarray(0, 5)).to.deep.equal(Buffer.from('caf\xe9\n', 'latin1'));
    expect(relabelled.toString('latin1')).to.equal(
      'caf\xe9\n<<<<<<< Your changes\n\xff\xfe\n=======\nX\n>>>>>>> Generated by APIMatic\n'
    );
  });
});

describe('settleMarkers, line by line', () => {
  const resolveMarkers = (content: string, side: 'yours' | 'generated') =>
    text(settleMarkers(bytes(content), side) ?? bytes(content));

  it('keeps the side asked for in every block, and every line outside the blocks', () => {
    const content =
      'before\n<<<<<<< Your changes\nmine 1\n=======\ntheirs 1\n>>>>>>> Generated by APIMatic\n' +
      'between\n<<<<<<< Your changes\nmine 2a\nmine 2b\n=======\ntheirs 2\n>>>>>>> Generated by APIMatic\nafter\n';

    expect(resolveMarkers(content, 'generated')).to.equal('before\ntheirs 1\nbetween\ntheirs 2\nafter\n');
    expect(resolveMarkers(content, 'yours')).to.equal('before\nmine 1\nbetween\nmine 2a\nmine 2b\nafter\n');
  });

  it('reads markers on CRLF lines, keeping the line endings', () => {
    const content = 'a\r\n<<<<<<< Your changes\r\nmine\r\n=======\r\ntheirs\r\n>>>>>>> Generated by APIMatic\r\nb\r\n';

    expect(resolveMarkers(content, 'yours')).to.equal('a\r\nmine\r\nb\r\n');
  });

  it('leaves a file without markers alone, CRLF included', () => {
    expect(resolveMarkers('a\r\nb\r\n', 'generated')).to.equal('a\r\nb\r\n');
    expect(resolveMarkers('', 'yours')).to.equal('');
  });

  it('leaves a file whole when a marker line was removed by hand, for either side', () => {
    const noMiddle = 'a\n<<<<<<< Your changes\nmine\ntheirs\n>>>>>>> Generated by APIMatic\nb\n';
    const noEnd = 'a\n<<<<<<< Your changes\nmine\n=======\ntheirs\nb\n';
    const noStart = 'a\nmine\n=======\ntheirs\n>>>>>>> Generated by APIMatic\nb\n';

    for (const side of ['yours', 'generated'] as const) {
      expect(resolveMarkers(noMiddle, side), `no middle, ${side}`).to.equal(noMiddle);
      expect(resolveMarkers(noEnd, side), `no end, ${side}`).to.equal(noEnd);
      expect(resolveMarkers(noStart, side), `no start, ${side}`).to.equal(noStart);
    }
  });
});

describe('settleMarkers', () => {
  it('settles the markers in a file that is not UTF-8, keeping its other bytes', () => {
    const content = Buffer.from(
      'caf\xe9\n<<<<<<< Your changes\n\xff\n=======\n\xfe\n>>>>>>> Generated by APIMatic\n',
      'latin1'
    );

    const settled = settleMarkers(new Uint8Array(content), 'generated');

    expect(Buffer.from(settled!).toString('latin1')).to.equal('caf\xe9\n\xfe\n');
    expect(settleMarkers(bytes('no markers\n'), 'yours')).to.be.undefined;
  });
});
