import { Buffer } from 'node:buffer';
import { TextDecoder, TextEncoder } from 'node:util';
import { expect } from 'chai';
import { settledContent, UnresolvedFile } from '../../../src/types/sdk/unresolved-file.js';

const bytes = (text: string) => new TextEncoder().encode(text);
const text = (content: Uint8Array | undefined) =>
  content === undefined ? undefined : new TextDecoder().decode(content);

const MARKED = 'top\n<<<<<<< Your changes\nmine\n=======\ntheirs\n>>>>>>> Generated by APIMatic\nbottom\n';

const file = (disk?: string, yours?: string, generated?: string): UnresolvedFile => ({
  disk: disk === undefined ? undefined : bytes(disk),
  yours: yours === undefined ? undefined : bytes(yours),
  generated: generated === undefined ? undefined : bytes(generated)
});

describe('settledContent', () => {
  it('settles the markers still in a file for either side, keeping the lines around them', () => {
    const marked = file(MARKED, 'yours', 'generated');

    expect(text(settledContent('generated', marked))).to.equal('top\ntheirs\nbottom\n');
    expect(text(settledContent('yours', marked))).to.equal('top\nmine\nbottom\n');
  });

  it('keeps a text file whose markers are gone, whichever side is asked for', () => {
    const resolved = file('resolved by hand', 'yours', 'generated');

    expect(text(settledContent('generated', resolved))).to.equal('resolved by hand');
    expect(text(settledContent('yours', resolved))).to.equal('resolved by hand');
    expect(settledContent('generated', file(undefined, 'yours', 'generated'))).to.be.undefined;
  });

  it('keeps a file the generator no longer produces, as it is on disk, for either side', () => {
    const dropped = file('your edited file, edited again', 'your edited file', undefined);

    expect(text(settledContent('generated', dropped))).to.equal('your edited file, edited again');
    expect(text(settledContent('yours', dropped))).to.equal('your edited file, edited again');
    expect(settledContent('generated', file(undefined, 'your edited file', undefined))).to.be.undefined;
  });

  it('keeps a file you deleted deleted for your side, and has the generator’s version for its own', () => {
    expect(settledContent('yours', file('generated version', undefined, 'generated version'))).to.be.undefined;
    expect(text(settledContent('generated', file('generated version', undefined, 'generated version')))).to.equal(
      'generated version'
    );
    expect(text(settledContent('generated', file(undefined, undefined, 'generated version')))).to.equal(
      'generated version'
    );
  });

  it('takes the side’s version of a binary file, which git never merges line by line', () => {
    const binary = file('yours\0', 'yours\0', 'generated\0');

    expect(text(settledContent('generated', binary))).to.equal('generated\0');
    expect(text(settledContent('yours', binary))).to.equal('yours\0');
  });

  it('settles a file that is not UTF-8 like any other, and keeps one without markers as it is', () => {
    const marked = new Uint8Array(Buffer.from(`\xff\n${MARKED}`, 'latin1'));
    const plain = { disk: new Uint8Array([0xff, 0xfe, 0x41]), yours: bytes('yours'), generated: bytes('generated') };

    const settled = settledContent('generated', { ...plain, disk: marked });

    expect(Buffer.from(settled!).toString('latin1')).to.equal('\xff\ntop\ntheirs\nbottom\n');
    expect(settledContent('generated', plain)).to.equal(plain.disk);
  });
});
