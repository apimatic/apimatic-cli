import { Buffer } from 'node:buffer';
import { expect } from 'chai';
import { Side } from '../../../src/types/sdk/conflict-markers.js';
import { UnresolvedFile } from '../../../src/types/sdk/unresolved-file.js';
import { bytes, named, NO_FILES, rel, written } from '../../helpers/merge.js';

const MARKED = 'top\n<<<<<<< Your changes\nmine\n=======\ntheirs\n>>>>>>> Generated by APIMatic\nbottom\n';
const PATH = rel('a.ts');

const maybe = (value: string | undefined) => (value === undefined ? undefined : bytes(value));
const file = (disk?: string, yours?: string, generated?: string) =>
  new UnresolvedFile(PATH, maybe(disk), maybe(yours), maybe(generated));
/** What settling for `side` does to the disk: the file written as text, removed, or left alone. */
const settled = (side: Side, unresolved: UnresolvedFile) => {
  const settlement = unresolved.settledFor(side);
  const writes = written(settlement.writes());
  const removes = settlement.removes().map(String);
  return writes.length > 0 ? writes[0][1] : removes.length > 0 ? 'removed' : 'left alone';
};

describe('UnresolvedFile.settledFor', () => {
  it('settles the markers still in a file for either side, keeping the lines around them, counted as merged', () => {
    const marked = file(MARKED, 'yours', 'generated');

    expect(settled('generated', marked)).to.equal('top\ntheirs\nbottom\n');
    expect(settled('yours', marked)).to.equal('top\nmine\nbottom\n');
    expect(named(marked.settledFor('yours').countedIn(NO_FILES)).merged).to.deep.equal(['a.ts']);
  });

  it('leaves a text file whose markers are gone alone, whichever side is asked for', () => {
    const resolved = file('resolved by hand', 'yours', 'generated');

    expect(settled('generated', resolved)).to.equal('left alone');
    expect(settled('yours', resolved)).to.equal('left alone');
    expect(settled('generated', file(undefined, 'yours', 'generated'))).to.equal('left alone');
  });

  it('leaves a file the generator no longer produces as it is on disk, for either side', () => {
    const dropped = file('your edited file, edited again', 'your edited file', undefined);

    expect(settled('generated', dropped)).to.equal('left alone');
    expect(settled('yours', dropped)).to.equal('left alone');
    expect(named(dropped.settledFor('generated').countedIn(NO_FILES)).kept).to.deep.equal(['a.ts']);
  });

  it('removes a file you deleted for your side, and writes the generator’s version for its own', () => {
    const deleted = file('generated version', undefined, 'generated version');

    expect(settled('yours', deleted)).to.equal('removed');
    expect(settled('generated', deleted)).to.equal('generated version');
    expect(settled('generated', file(undefined, undefined, 'generated version'))).to.equal('generated version');
    expect(named(deleted.settledFor('generated').countedIn(NO_FILES)).updated).to.deep.equal(['a.ts']);
  });

  it('takes the side’s version of a binary file, which git never merges line by line', () => {
    const binary = file('yours\0', 'yours\0', 'generated\0');

    expect(settled('generated', binary)).to.equal('generated\0');
    expect(settled('yours', binary)).to.equal('left alone');
  });

  it('settles a file that is not UTF-8 like any other', () => {
    const marked = new Uint8Array(Buffer.from(`\xff\n${MARKED}`, 'latin1'));

    const content = new UnresolvedFile(PATH, marked, bytes('yours'), bytes('generated')).settledFor('generated');

    expect(Buffer.from(content.writes()[0].content).toString('latin1')).to.equal('\xff\ntop\ntheirs\nbottom\n');
  });
});
