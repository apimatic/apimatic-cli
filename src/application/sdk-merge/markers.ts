import { TextDecoder, TextEncoder } from 'node:util';

export const YOURS_MARKER = '<<<<<<< Your changes';
export const GENERATED_MARKER = '>>>>>>> Generated by APIMatic';

const decoder = new TextDecoder('utf-8', { fatal: true });
const encoder = new TextEncoder();

/**
 * Git labels a conflict with the ids of the two commits it merged; the file the developer
 * opens names the sides instead. Only marker lines change, so the rest of the file is byte for
 * byte what git produced.
 */
export function relabelMarkers(content: Uint8Array): Uint8Array {
  const text = decoder.decode(content);
  const relabelled = text
    .replace(/^<<<<<<< [0-9a-f]{40}$/gm, YOURS_MARKER)
    .replace(/^>>>>>>> [0-9a-f]{40}$/gm, GENERATED_MARKER);
  return relabelled === text ? content : encoder.encode(relabelled);
}

/** Whether `content` still carries the markers a conflicted run writes. */
export function hasConflictMarkers(content: Uint8Array): boolean {
  let text: string;
  try {
    text = decoder.decode(content);
  } catch {
    return false;
  }
  return text.split(/\r?\n/).some((line) => line === YOURS_MARKER || line === GENERATED_MARKER);
}
