import { isObjectId } from '../git/object-id.js';
import { asBytes, asText } from './file-content.js';

/** Whose lines win where you and the generator changed the same ones. */
export type Side = 'yours' | 'generated';

const OPEN = '<<<<<<< ';
const MIDDLE = '=======';
const CLOSE = '>>>>>>> ';
const YOURS_LABEL = 'Your changes';
const GENERATED_LABEL = 'Generated by APIMatic';

/** The markers as the CLI writes them, naming the sides rather than the two commits git merged. */
export const YOURS_MARKER = `${OPEN}${YOURS_LABEL}`;
export const GENERATED_MARKER = `${CLOSE}${GENERATED_LABEL}`;

type Tag = 'plain' | 'open' | 'middle' | 'close' | Side;

/** One line of the file, which keeps its own trailing CR, and the part of a marker block it is. */
type Line = { text: string; tag: Tag };

// Git labels a side with the id of the commit it merged, followed by `:path` where the file was renamed.
const isLabel = (label: string, own: string): boolean => label === own || isObjectId(label.replace(/:.*$/, ''));

const bare = (text: string): string => (text.endsWith('\r') ? text.slice(0, -1) : text);

/** Each line tagged by the part of a block it is in; none for a file without a block, or whose markers are not well formed. */
function tagged(texts: readonly string[]): Line[] | undefined {
  const lines: Line[] = [];
  let inside: 'plain' | Side = 'plain';
  let opened = false;
  for (const text of texts) {
    const line = bare(text);
    if (line.startsWith(OPEN) && isLabel(line.slice(OPEN.length), YOURS_LABEL)) {
      if (inside !== 'plain') {
        return undefined;
      }
      lines.push({ text, tag: 'open' });
      inside = 'yours';
      opened = true;
    } else if (line === MIDDLE && inside === 'yours') {
      lines.push({ text, tag: 'middle' });
      inside = 'generated';
    } else if (line.startsWith(CLOSE) && isLabel(line.slice(CLOSE.length), GENERATED_LABEL)) {
      if (inside !== 'generated') {
        return undefined;
      }
      lines.push({ text, tag: 'close' });
      inside = 'plain';
    } else {
      lines.push({ text, tag: inside });
    }
  }
  return opened && inside === 'plain' ? lines : undefined;
}

const CLI_MARKERS: Readonly<Record<'open' | 'close', string>> = { open: YOURS_MARKER, close: GENERATED_MARKER };

const relabel = (line: Line): string =>
  line.tag === 'open' || line.tag === 'close'
    ? `${CLI_MARKERS[line.tag]}${line.text.endsWith('\r') ? '\r' : ''}`
    : line.text;

/**
 * A file as git merged it, read line by line so its marker blocks are known: a block holds your lines,
 * then the generator's. A file without a block, or whose markers are not well formed, is left as it is.
 */
export class MergedText {
  /** The lines by block part, or none for a file without a well-formed block, which every query answers with the very bytes given. */
  private constructor(private readonly bytes: Uint8Array, private readonly lines: readonly Line[]) {}

  public static parse(content: Uint8Array): MergedText {
    return new MergedText(content, tagged(asText(content).split('\n')) ?? []);
  }

  public hasMarkers(): boolean {
    return this.lines.length > 0;
  }

  /** The file with the CLI's labels on its markers; the very bytes given when there are none. */
  public relabelled(): Uint8Array {
    return this.hasMarkers() ? asBytes(this.lines.map(relabel).join('\n')) : this.bytes;
  }

  /** The file with each block settled for `side`, every line outside the blocks kept; the very bytes given when there are none. */
  public settledFor(side: Side): Uint8Array {
    if (!this.hasMarkers()) {
      return this.bytes;
    }
    const kept = this.lines.filter((line) => line.tag === 'plain' || line.tag === side);
    return asBytes(kept.map((line) => line.text).join('\n'));
  }
}
