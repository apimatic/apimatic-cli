import { TextDecoder, TextEncoder } from 'node:util';

export const YOURS_MARKER = '<<<<<<< Your changes';
export const GENERATED_MARKER = '>>>>>>> Generated by APIMatic';

const decoder = new TextDecoder('utf-8', { fatal: true });
const encoder = new TextEncoder();

/**
 * Git labels a conflict with the ids of the two commits it merged; the file the developer
 * opens names the sides instead. Only marker lines change, so the rest of the file is byte for
 * byte what git produced.
 */
export function relabelMarkers(content: Uint8Array): Uint8Array {
  const text = decoder.decode(content);
  const relabelled = text
    .replace(/^<<<<<<< [0-9a-f]{40}$/gm, YOURS_MARKER)
    .replace(/^>>>>>>> [0-9a-f]{40}$/gm, GENERATED_MARKER);
  return relabelled === text ? content : encoder.encode(relabelled);
}

/**
 * The file with every marker block settled for the generator's side: your side of each block
 * goes, the generator's stays, and every line outside the markers, including what you already
 * resolved by hand, is left as it is.
 */
export function resolveMarkersForGenerated(content: string): string {
  const resolved: string[] = [];
  let inside: 'none' | 'yours' | 'generated' = 'none';
  for (const line of content.split('\n')) {
    const bare = line.endsWith('\r') ? line.slice(0, -1) : line;
    if (inside === 'none' && bare === YOURS_MARKER) {
      inside = 'yours';
    } else if (inside === 'yours' && bare === '=======') {
      inside = 'generated';
    } else if (inside === 'generated' && bare === GENERATED_MARKER) {
      inside = 'none';
    } else if (inside !== 'yours') {
      resolved.push(line);
    }
  }
  return resolved.join('\n');
}
